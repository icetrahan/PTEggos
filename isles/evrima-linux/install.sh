#!/bin/bash
# Primal - The Isle: Evrima install script (LINUX egg, standard Wings node).
# Runs as root in ghcr.io/parkervcp/installers:debian with the server volume
# mounted at /mnt/server.
#
# WHAT "INSTALLED" MEANS HERE (BUGS #346 - the customer-#3 onboarding gate,
# ported from egg 40's install.ps1): the gate is the binary the WRAPPER
# launches, checked from the consumer's own path, and a failure exits 1 with a
# CLASS that says what to do about it. Only the terminal gate prints a success
# line. Nothing infers success from the absence of an error - steamcmd's
# non-zero exit does not stop a bash script without set -e, which is exactly
# how the 2026-07-28 incident reported a dead install as complete.
#
# The MODDED binary is NOT fetched here - the boot wrapper replaces the
# Shipping binary from the Primal API on every start, before launch. Install
# ends with the vanilla binary on disk; it is never launched.

SRV=/mnt/server
GAME_BINARY="$SRV/TheIsle/Binaries/Linux/TheIsleServer-Linux-Shipping"
PRIM="$SRV/_primal"
mkdir -p "$SRV/steamcmd" "$SRV/steamapps" "$PRIM" "$SRV/TheIsle/Saved/Config/LinuxServer"

STEAM_EXITS=""
MAX_TRIES=5

tcp_probe() { # $1 host, $2 port. Reachable = curl got a TCP connection
    # (any outcome except DNS-fail 6 / connect-refused 7 / timeout 28).
    local rc
    curl -s --connect-timeout 6 -o /dev/null "https://$1:${2:-443}" 2>/dev/null
    rc=$?
    [ "$rc" -ne 6 ] && [ "$rc" -ne 7 ] && [ "$rc" -ne 28 ]
}
dns_probe() { getent hosts "$1" >/dev/null 2>&1; }

fail_install() { # $1 class, $2 summary, rest = next-step lines
    local CLASS="$1" SUMMARY="$2"; shift 2
    echo ""
    echo "================================================================"
    echo "INSTALL FAILED [$CLASS]"
    echo "================================================================"
    echo "$SUMMARY"
    echo ""
    echo "Evidence:"
    echo "  steamcmd attempt exits : ${STEAM_EXITS:-(never ran)}"
    echo "  shipping binary        : $([ -f "$GAME_BINARY" ] && stat -c%s "$GAME_BINARY" || echo MISSING) "
    echo "  free disk on volume    : $(df -BG --output=avail "$SRV" 2>/dev/null | tail -1 | tr -d ' ')"
    echo "  DNS api.steampowered.com: $(dns_probe api.steampowered.com && echo ok || echo BROKEN)"
    echo "  TCP 1.1.1.1:443        : $(tcp_probe 1.1.1.1 && echo ok || echo DOWN)  (generic outbound)"
    echo "  TCP steamcdn           : $(tcp_probe steamcdn-a.akamaihd.net && echo ok || echo DOWN)"
    if [ $# -gt 0 ]; then
        echo ""
        echo "What to do:"
        for L in "$@"; do echo "  - $L"; done
    fi
    echo ""
    echo "This install did NOT complete. There is no bootable server binary."
    echo "Exiting 1 so the panel marks the install FAILED instead of ready."
    echo "================================================================"
    exit 1
}

echo "Downloading SteamCMD..."
cd /tmp || exit 1
curl -sSL -o steamcmd.tar.gz https://steamcdn-a.akamaihd.net/client/installer/steamcmd_linux.tar.gz
tar -xzf steamcmd.tar.gz -C "$SRV/steamcmd"
cd "$SRV/steamcmd" || exit 1
chown -R root:root /mnt
export HOME="$SRV"
[ -f ./steamcmd.sh ] || fail_install STEAMCMD-MISSING \
    "steamcmd_linux.tar.gz downloaded and extracted, but steamcmd.sh is not there." \
    "Valve changed the tarball layout, or the extract was blocked. Reinstall to retry."

echo "Bootstrapping SteamCMD (self-update)..."
./steamcmd.sh +quit
echo "(steamcmd) bootstrap exit code: $?"

# The Isle's first app_update reliably fails with "Missing configuration"
# (Steam app-config not cached yet). Retry until the Shipping binary appears.
for i in $(seq 1 $MAX_TRIES); do
    echo "Installing The Isle: Evrima (app 412680, evrima) - attempt $i/$MAX_TRIES (~1.7GB)..."
    ./steamcmd.sh +force_install_dir "$SRV" +login anonymous +app_update 412680 -beta evrima validate +quit
    EC=$?
    STEAM_EXITS="${STEAM_EXITS:+$STEAM_EXITS, }$EC"
    echo "(steamcmd) attempt $i exit code: $EC"
    [ -f "$GAME_BINARY" ] && { echo "The Isle server files present (Shipping binary found)."; break; }
    if [ "$i" -ge 2 ]; then
        # Self-heal a corrupt appmanifest / half-written 'downloading' - but
        # ONLY if Steam is actually reachable. On a dead link the partial is
        # fine and deleting it is pure wasted egress (#346).
        if tcp_probe steamcdn-a.akamaihd.net; then
            echo "(self-heal) still missing after retry - deleting steamapps for a clean re-fetch..."
            rm -rf "$SRV/steamapps"
        else
            echo "(self-heal) SKIPPED: Steam is unreachable from this box right now, so the"
            echo "(self-heal) partial download is not corrupt - keeping steamapps (#346)."
        fi
    else
        echo "app not installed yet (Steam config warming up); retrying in 10s..."
    fi
    sleep 10
done

# Steam SDK shims (same as every Linux egg here)
mkdir -p "$SRV/.steam/sdk32" "$SRV/.steam/sdk64"
cp -v linux32/steamclient.so "$SRV/.steam/sdk32/steamclient.so" 2>/dev/null || true
cp -v linux64/steamclient.so "$SRV/.steam/sdk64/steamclient.so" 2>/dev/null || true

# ---------------------------------------------------------------------------
# Primal helper files (boot wrapper + config templates), from base64 so this
# script is self-contained in the panel DB. DO NOT EDIT THE BLOBS BY HAND -
# edit the loose files in PTEggos isles/evrima-linux/ and run embed.py, which
# regenerates the blobs AND the sha256 lines below. Each write is sha-verified:
# a corrupted blob must fail the install, not boot garbage (rule 13).
# ---------------------------------------------------------------------------
echo "Writing Primal helper files (config templates + startup wrapper)..."

write_blob() { # $1 = dest path, $2 = expected sha256; blob on stdin
    base64 -d > "$1" || fail_install BLOB-DECODE-FAILED \
        "base64 decode failed for $1 - the egg install script is corrupted." \
        "Re-import the egg from PTEggos isles/evrima-linux/ and Reinstall."
    local GOT
    GOT=$(sha256sum "$1" | awk '{print $1}')
    if [ "$GOT" != "$2" ]; then
        fail_install BLOB-SHA-MISMATCH \
            "$1 decoded but its sha256 does not match the recorded one (got $GOT)." \
            "Re-import the egg from PTEggos isles/evrima-linux/ and Reinstall."
    fi
}

