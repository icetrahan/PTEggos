    echo "  THE GATE  TheIsle/Binaries/Linux/TheIsleServer-Linux-Shipping : present, $SSIZE B"
    if [ "$SSIZE" -gt 157286400 ]; then
        echo ""
        echo "OK: TheIsleServer-Linux-Shipping present ($SSIZE B)."
        echo "Install complete."
        exit 0
    fi
    fail_install TRUNCATED-BINARY \
        "The Shipping binary exists but is only $SSIZE bytes (<150MB), so the server cannot boot." \
        "Reinstall (admin: Toggle Install Status, then Reinstall) to re-pull it."
fi
echo "  THE GATE  TheIsle/Binaries/Linux/TheIsleServer-Linux-Shipping : MISSING"

# --- the install produced no bootable server: diagnose, then exit 1 ---------
GENERIC_OK=$(tcp_probe 1.1.1.1 && echo 1 || echo 0)
STEAM_OK=$(tcp_probe steamcdn-a.akamaihd.net && echo 1 || echo 0)
DNS_OK=$(dns_probe api.steampowered.com && echo 1 || echo 0)
FREE_GB=$(df -BG --output=avail "$SRV" 2>/dev/null | tail -1 | tr -dc '0-9')

if [ "$GENERIC_OK" = "0" ] && [ "$STEAM_OK" = "0" ]; then
    fail_install NO-OUTBOUND \
        "This box has NO outbound connectivity - not even to 1.1.1.1. steamcmd could not have downloaded anything (the 2026-07-28 shape, BUGS #346/#347)." \
        "Check the host provider DDoS mitigation FIRST (ReliableSite false-positived on steamcmd on 2026-07-28)." \
        "If the panel stays stuck on 'installing', the recovery is admin: Toggle Install Status, then Reinstall." \
        "Restore connectivity, then Reinstall."
fi
if [ "$DNS_OK" = "0" ] && [ "$GENERIC_OK" = "1" ]; then
    fail_install DNS-BROKEN \
        "Raw outbound works but Steam hostnames do not resolve, so steamcmd cannot find Steam." \
        "Fix the container/node DNS resolver, then Reinstall."
fi
if [ "$GENERIC_OK" = "1" ] && [ "$STEAM_OK" = "0" ]; then
    fail_install STEAM-UNREACHABLE \
        "General outbound works, but Steam specifically is unreachable from this box." \
        "Check https://steamstat.us for a Steam-side outage." \
        "If Steam is up, suspect firewall/DDoS filtering on the Steam ranges, then Reinstall."
fi
if [ -n "$FREE_GB" ] && [ "$FREE_GB" -lt 10 ]; then
    fail_install DISK-FULL \
        "Only ${FREE_GB} GB free. The Evrima install needs roughly 70 GB and ran out of room." \
        "Free space on the node or move this server to a bigger volume, then Reinstall."
fi
fail_install STEAMCMD-FAILED \
    "Steam is reachable but all $MAX_TRIES steamcmd attempts produced no Shipping binary." \
    "Read the steamcmd exit codes above and the attempt output for the real error." \
    "A 'Missing configuration' / 'No subscription' run means app 412680 -beta evrima refused anonymous login - verify the branch still exists." \
    "Then Reinstall."
